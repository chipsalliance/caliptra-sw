use caliptra_ocp_eat::cbor::{CborEncoder, TaggedOid};
use caliptra_ocp_eat::cose::{CoseSign1, ProtectedHeader};
use caliptra_ocp_eat::csr_eat::{
    oids, CsrEatClaims, KeyAttributeEntry, KeyPairInventoryClaims, KeyPairInventoryEntry,
};
use caliptra_ocp_eat::{cbor_bstr_header, cbor_tags};
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

/// GET_ATTESTED_PQ_CSR key ID for the PQ.DevID keypair. Must match
/// `GetAttestedPqCsrReq::KEY_ID_PQ_DEVID` in caliptra-api.
const PQ_DEVID_KEYPAIR_ID: u8 = 1;

/// OCP derivation-component bitfield for PQ.DevID.
///
/// The PQ.DevID CDI is derived solely from the SoC-provisioned `PQ.DevID.Seed`
/// (see SET_PQ_SEED). None of the OCP-defined derivation components (UDS,
/// field entropy, non-confidential fuses, FMC, runtime firmware) are inputs, so
/// no bits are set.
const PQ_DEVID_DERIVATION_BITFIELD: u64 = 0;

/// Length of a CBOR byte-string header for a 256..=65535 byte payload
/// (0x59, len_hi, len_lo). Markers below are sized to force this header.
const MARKER_BSTR_HEADER_LEN: usize = 3;
const MARKER_LEN: usize = 300;

fn find_subslice(haystack: &[u8], needle: &[u8]) -> Option<usize> {
    haystack.windows(needle.len()).position(|w| w == needle)
}

fn write_bytes_const(out: &mut String, name: &str, bytes: &[u8]) {
    out.push_str(&format!("pub const {name}: [u8; {}] = [", bytes.len()));
    for (i, byte) in bytes.iter().enumerate() {
        if i % 12 == 0 {
            out.push_str("\n    ");
        }
        out.push_str(&format!("0x{byte:02x}, "));
    }
    out.push_str("\n];\n\n");
}

/// Generate the CBOR/COSE byte templates used by GET_ATTESTED_PQ_CSR.
///
/// The firmware does not link the OCP EAT encoder. Instead the encoder is run
/// here with marker values; the bytes surrounding each marker are emitted as
/// constants and the firmware splices the runtime values (nonce, CSR, key ID,
/// signature) in between.
fn generate_attested_csr_templates(out_dir: &Path) {
    let mut generated = String::new();
    generated.push_str("// Licensed under the Apache-2.0 license\n");
    generated.push_str("// AUTO-GENERATED FILE. DO NOT EDIT.\n");
    generated.push_str("// Generated by runtime build.rs from caliptra-ocp-eat\n\n");

    generated.push_str(&format!(
        "pub const CBOR_MAX_INLINE_LEN: usize = {};\n\
         pub const CBOR_BYTE_STRING_TINY_BASE: u8 = 0x{:02x};\n\
         pub const CBOR_BYTE_STRING_1BYTE_LEN: u8 = 0x{:02x};\n\
         pub const CBOR_BYTE_STRING_2BYTE_LEN: u8 = 0x{:02x};\n\
         /// Longest byte-string header emitted at runtime (payloads up to 65535 bytes).\n\
         pub const CBOR_MAX_BSTR_HEADER_LEN: usize = {};\n\n",
        cbor_bstr_header::MAX_INLINE_LEN,
        cbor_bstr_header::TINY_BASE,
        cbor_bstr_header::LEN_1BYTE,
        cbor_bstr_header::LEN_2BYTE,
        CborEncoder::estimate_uint_size(u16::MAX as u64),
    ));

    let marker_nonce = [0xa5u8; 32];
    let pq_devid_attrs = [KeyAttributeEntry::new(
        TaggedOid::new(oids::OCP_SECURITY_OID_KDA),
        PQ_DEVID_DERIVATION_BITFIELD,
    )];

    // 1. KeyPair inventory discovery template (key_id == 0)
    let entries = [KeyPairInventoryEntry::new(
        PQ_DEVID_KEYPAIR_ID,
        &pq_devid_attrs,
    )];
    let inventory = KeyPairInventoryClaims::with_nonce(&entries, &marker_nonce).unwrap();
    let mut inv_buf = [0u8; 512];
    let inv_len = {
        let mut inv_enc = CborEncoder::new(&mut inv_buf);
        inventory.encode(&mut inv_enc).unwrap();
        inv_enc.len()
    };
    let inv_encoded = &inv_buf[..inv_len];
    let inv_nonce_pos = find_subslice(inv_encoded, &marker_nonce).expect("inventory nonce marker");
    write_bytes_const(
        &mut generated,
        "KEYPAIR_INVENTORY_PREFIX",
        &inv_encoded[..inv_nonce_pos],
    );
    write_bytes_const(
        &mut generated,
        "KEYPAIR_INVENTORY_SUFFIX",
        &inv_encoded[inv_nonce_pos + marker_nonce.len()..],
    );

    // 2. PQ.DevID CSR EAT template (key_id == 1)
    let marker_csr = [0x5cu8; MARKER_LEN];
    let claims = CsrEatClaims::with_nonce(&marker_csr, &pq_devid_attrs, &marker_nonce);
    let mut csr_buf = [0u8; 1024];
    let csr_len = {
        let mut csr_enc = CborEncoder::new(&mut csr_buf);
        claims.encode(&mut csr_enc).unwrap();
        csr_enc.len()
    };
    let csr_encoded = &csr_buf[..csr_len];
    let csr_nonce_pos = find_subslice(csr_encoded, &marker_nonce).expect("csr nonce marker");
    let csr_data_pos = find_subslice(csr_encoded, &marker_csr).expect("csr data marker");
    assert_eq!(
        csr_encoded[csr_data_pos - MARKER_BSTR_HEADER_LEN],
        cbor_bstr_header::LEN_2BYTE,
        "marker_csr must have a 3-byte CBOR byte string header"
    );
    write_bytes_const(
        &mut generated,
        "CSR_EAT_PREFIX",
        &csr_encoded[..csr_nonce_pos],
    );
    // Bytes between the nonce and the CSR bstr header (the CLAIM_KEY_ATTESTED_CSR key).
    write_bytes_const(
        &mut generated,
        "CSR_EAT_CLAIM_KEY_CSR",
        &csr_encoded[csr_nonce_pos + marker_nonce.len()..csr_data_pos - MARKER_BSTR_HEADER_LEN],
    );
    write_bytes_const(
        &mut generated,
        "CSR_EAT_SUFFIX_PQ_DEVID",
        &csr_encoded[csr_data_pos + MARKER_LEN..],
    );

    // 3. COSE_Sign1 and Sig_structure templates for ES384 (RT Alias key)
    let marker_kid = [0x7du8; 20];
    let marker_payload = [0x8eu8; MARKER_LEN];
    let marker_sig = [0x9fu8; 96];

    let mut protected_header = ProtectedHeader::new_es384();
    protected_header.kid = Some(&marker_kid);

    // Sig_structure
    let mut sig_buf = vec![0u8; 2048];
    let cose_for_sig = CoseSign1::new(&mut sig_buf)
        .protected_header(&protected_header)
        .payload(&marker_payload);
    let mut sig_ctx = vec![0u8; 2048];
    let sig_ctx_len = cose_for_sig.get_signature_context(&mut sig_ctx).unwrap();
    let sig_ctx = &sig_ctx[..sig_ctx_len];
    let sig_kid_pos = find_subslice(sig_ctx, &marker_kid).expect("sig kid marker");
    let sig_payload_pos = find_subslice(sig_ctx, &marker_payload).expect("sig payload marker");
    assert_eq!(
        sig_ctx[sig_payload_pos - MARKER_BSTR_HEADER_LEN],
        cbor_bstr_header::LEN_2BYTE,
        "marker_payload in Sig_structure must have a 3-byte CBOR byte string header"
    );
    write_bytes_const(
        &mut generated,
        "SIG_PREAMBLE_ECC_BEFORE_KID",
        &sig_ctx[..sig_kid_pos],
    );
    write_bytes_const(
        &mut generated,
        "SIG_ECC_AFTER_KID_BEFORE_PAYLOAD_LEN",
        &sig_ctx[sig_kid_pos + marker_kid.len()..sig_payload_pos - MARKER_BSTR_HEADER_LEN],
    );

    // COSE_Sign1 envelope (CWT-tagged)
    let mut cose_buf = vec![0u8; 2048];
    let cose = CoseSign1::new(&mut cose_buf)
        .protected_header(&protected_header)
        .payload(&marker_payload)
        .signature(&marker_sig);
    let cose_len = cose.encode(Some(&[cbor_tags::CWT])).unwrap();
    let cose = &cose_buf[..cose_len];
    let cose_kid_pos = find_subslice(cose, &marker_kid).expect("cose kid marker");
    let cose_payload_pos = find_subslice(cose, &marker_payload).expect("cose payload marker");
    let cose_sig_pos = find_subslice(cose, &marker_sig).expect("cose sig marker");
    assert_eq!(
        cose[cose_payload_pos - MARKER_BSTR_HEADER_LEN],
        cbor_bstr_header::LEN_2BYTE,
        "marker_payload in COSE_Sign1 must have a 3-byte CBOR byte string header"
    );
    assert_eq!(
        cose_sig_pos + marker_sig.len(),
        cose.len(),
        "signature must be the last element of the COSE_Sign1 envelope"
    );
    write_bytes_const(
        &mut generated,
        "COSE_PREAMBLE_ECC_BEFORE_KID",
        &cose[..cose_kid_pos],
    );
    write_bytes_const(
        &mut generated,
        "COSE_ECC_AFTER_KID_BEFORE_PAYLOAD_LEN",
        &cose[cose_kid_pos + marker_kid.len()..cose_payload_pos - MARKER_BSTR_HEADER_LEN],
    );
    write_bytes_const(
        &mut generated,
        "COSE_ECC_SIG_BSTR_HEADER",
        &cose[cose_payload_pos + MARKER_LEN..cose_sig_pos],
    );

    fs::write(out_dir.join("attested_csr_template.rs"), generated)
        .expect("Failed to write attested_csr_template.rs");
}

fn main() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    generate_attested_csr_templates(&out_dir);
    println!("cargo:rerun-if-changed=build.rs");

    cfg_if::cfg_if! {
        if #[cfg(not(feature = "std"))] {
            use caliptra_gen_linker_scripts::gen_memory_x;

            fs::write(out_dir.join("memory.x"),gen_memory_x(caliptra_common::RUNTIME_ORG, caliptra_common::RUNTIME_SIZE)
            .as_bytes())
            .expect("Unable to generate memory.x");


            println!("cargo:rustc-link-search={}", out_dir.display());

            println!("cargo:rerun-if-changed=memory.x");
            println!("cargo:rustc-link-arg=-Tmemory.x");

            println!("cargo:rustc-link-arg=-Tlink.x");
        }
    }
}
